"""The PS-1 probe analyses (``scripts/ps1_probe_analysis.py``) on SYNTHETIC inputs.

P1 on the stand-in engine (``tests/fixtures/ps1_probe_engine.py``), one game per stop behaviour: in place, refused,
ignored, entered first, transitions at and beyond the window's edges, no re-listing, a refused re-order, transitioning
units that do not count, a partly accepted group, a newly full back-off destination; the premise, the cross-checks
that refuse, the secondary outcomes. P2 on trajectories generated by the frozen model and its rivals
(``tests/fixtures/ps1_trajectories.py``): every targeted claim holds on M1c data and fails on its rival's, F1 and F2
pass on consistent data and fail on planted errors, the keep flag is set aside, removals, mixed speeds and game
lengths. The registered gate rules on every verdict combination they distinguish.
"""

from __future__ import annotations

import copy
import pickle
import unittest

from miaosuan_agent.boundary import MoveCosts, Origin
from miaosuan_agent.evaluation import ps1_model as pm

from tests.fixtures import ps1_probe_engine as pe
from tests.fixtures import ps1_trajectories as tr
from miaosuan_agent.experiments.deployment_split import CANDIDATE_ID as SPLIT_ID

an = tr.analysis
COSTS = MoveCosts.from_raw(pe.cost_data(), Origin.ENGINE)
TRIGGER_K = 23
S, R, I = "SUPPORTED", "REFUTED", "INCONCLUSIVE"
_BASE = []


def base():
    if not _BASE:
        _BASE.append(pe.play_probe(SPLIT_ID)[0])
    return _BASE[0]


def p1(manifest=None, plant=None, **options):
    record, compact, windows = pe.play_probe(**options)
    if plant:
        plant(record, compact, windows)
    return an.analyze_p1(an.Game(record, compact, windows), manifest or pe.manifest(), base(), COSTS)


class P1VerdictTableTest(unittest.TestCase):
    CASES = [
        ({}, {"accepted in place": 4}, (S, S, S, S)),
        ({"stop": "refused"}, {"refused": 4}, (R, I, I, I)),
        ({"stop": "ignored"}, {"no attributable change": 4}, (R, R, I, I)),
        ({"stop": "enter"}, {"accepted after entry": 4}, (S, R, I, R)),
        ({"transition": 73}, {"accepted in place": 4}, (S, S, R, S)),
        ({"transition": 74}, {"accepted in place": 4}, (S, S, S, S)),
        ({"transition": 77}, {"accepted in place": 4}, (S, S, S, S)),
        ({"transition": 78}, {"accepted in place": 4}, (S, S, R, S)),
        ({"relist": False}, {"accepted in place": 4}, (S, S, R, S)),
        ({"refuse_moves_after": 85}, {"accepted in place": 4}, (S, S, R, S)),
        ({"uncounted": True}, {"accepted in place": 4}, (S, S, S, R)),
        ({"uncounted_after": 10}, {"accepted in place": 4}, (S, S, S, R)),
        ({"per_unit": {pe.WAITERS[0]: "refused"}}, {"accepted in place": 3, "refused": 1}, (R, S, S, S)),
        ({"per_unit": {pe.WAITERS[1]: "ignored"}}, {"accepted in place": 3, "no attributable change": 1}, (R, R, S, S)),
        ({"fill": (95, 105, 4)}, {"accepted in place": 4}, (S, S, S, S)),
    ]

    def test_each_stop_behaviour_gives_its_registered_verdicts(self) -> None:
        for options, outcomes, verdicts in self.CASES:
            with self.subTest(options=options):
                pub = p1(**options)["public"]
                self.assertTrue(pub["premise"]["reproduced"])
                self.assertEqual(pub["outcomes"], outcomes)
                self.assertEqual(tuple(pub["verdicts"][e] for e in ("E1", "E2", "E3", "E4")), verdicts)

    def test_the_default_game_in_detail(self) -> None:
        result = p1()
        pub = result["public"]
        self.assertEqual((pub["trigger_k"], pub["trigger_cur_step"], pub["stops"]), (TRIGGER_K, 22, 4))
        self.assertEqual({u["L"] for u in pub["units"]}, {75})
        self.assertTrue(all(u["back_off"]["accepted"] and u["back_off"]["arrival_k"] for u in pub["units"]))
        self.assertTrue(all(u["listed_10"] and u["in_place"] for u in pub["units"]))
        self.assertEqual(pub["offline"]["pre_trigger_decisions_rechecked"], TRIGGER_K - 1)
        self.assertTrue(pub["trigger_recomputed"]["agrees_with_hook"])
        self.assertGreater(pub["E4"]["discriminating_unit_steps"], 0)
        sec = pub["secondary"]
        self.assertEqual((sec["deadlocked_at_trigger"], sec["trigger_cycle_lengths"]), (10, [2]))
        self.assertEqual(sec["trigger_cycle_absent_from_k"], TRIGGER_K + 1)  # the stopped group became holders
        self.assertEqual(len(sec["back_off_arrivals"]), 4)
        # the stand-in's units are already traversing at the first play decision, whose timing is not observed:
        # P1-S is reported as not computed and the registered E analysis is unaffected
        self.assertEqual((pub["p1_s"]["computed"], "traversing" in pub["p1_s"]["reason"]), (False, True))

    def test_a_restart_towards_a_hex_full_only_with_transitioning_units_refutes_e4(self) -> None:
        e4 = p1(uncounted_after=10)["public"]["E4"]
        self.assertGreater(e4["discriminating_unit_steps"], 0)  # first seen waiting
        self.assertGreater(e4["restarts"], 0)  # then restarting
        self.assertEqual(e4["verdict"], R)

    def test_a_newly_full_destination_leaves_the_new_move_untested(self) -> None:
        pub = p1(fill=(95, 105, 4))["public"]
        self.assertTrue(all(u["back_off"] is None and u["released"] == 1 for u in pub["units"]))


class P1PremiseTest(unittest.TestCase):
    def test_a_different_state_before_the_trigger_is_no_reproduction(self) -> None:
        tampered = copy.deepcopy(base())
