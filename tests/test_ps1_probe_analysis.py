class TargetedClaimTest(unittest.TestCase):
    def claims(self, case, rules):
        t, _ = case(rules)
        return an.targeted(t, 0, tr.line(5))["public"]

    def test_m1c_data(self) -> None:
        pub = self.claims(tr.contention_case, "M1c")
        self.assertEqual(pub["T-a"], {"discriminating": 2, "as_predicted": 2})
        self.assertEqual(pub["T-d"]["contention_events"], 1)
        self.assertEqual((pub["T-d"]["ascending_as_predicted"], pub["T-d"]["discriminating_from_first_come"]), (1, 1))
        self.assertEqual(pub["claims"]["T-e"], S)
        self.assertEqual(pub["claims"]["T-d"], "INSUFFICIENT")
        refill = self.claims(tr.refill_case, "M1c")
        self.assertEqual(refill["T-c"], {"discriminating": 1, "as_predicted": 1})
        self.assertEqual(refill["claims"]["T-c"], "INSUFFICIENT")

    def test_rival_models_are_refuted(self) -> None:
        self.assertEqual(self.claims(tr.contention_case, "M1b")["claims"]["T-a"], R)
        m1 = self.claims(tr.contention_case, "M1")["claims"]
        self.assertEqual((m1["T-a"], m1["T-b"]), (R, R))
        self.assertEqual(self.claims(tr.refill_case, "M1")["claims"]["T-b"], R)
        desc = self.claims(tr.contention_case, "descending")["claims"]
        self.assertEqual((desc["T-d"], desc["T-e"]), (R, R))
        self.assertEqual(self.claims(tr.refill_case, "descending")["claims"]["T-e"], R)

    def test_keep_flag_events_are_set_aside(self) -> None:
        t, _ = tr.contention_case("M1c")
        entry = next(k for k in t.ks[1:] if t.b[k][5].hex == 2 and t.b[k - 1][5].hex == 1)
        for channel in (t.b, t.a):
            channel[entry][5] = channel[entry][5]._replace(keep=1)
        pub = an.targeted(t, 0, tr.line(5))["public"]
        self.assertEqual(pub["T-a"]["discriminating"], 1)
        self.assertEqual(pub["entry_rule"]["entries with the keep flag set"], 1)

    def test_t_a_sets_aside_entries_whose_next_hex_lost_a_unit_in_the_step(self) -> None:
        row = lambda h, path=(), speed=0: an.Row(h, tuple(path), speed, 0, 0, tr.SPEED, 2, 0, 0, 1, frozenset())
        before = {1: row(3, (4,), 0.2), 2: row(1, (2, 3), 0.2), 3: row(5, (3,), 0.2),
                  **{u: row(3) for u in (7, 8, 9)}}
        after = {1: row(4), 2: row(2, (3,), 0.2), 3: row(3), **{u: row(3) for u in (7, 8, 9)}}
        ent = an.entry_events({0: before, 1: after}, [0, 1])
        self.assertEqual(ent["counts"]["entries with a path left"], 1)  # unit 2 entered hex 2
        self.assertEqual(ent["T-a"], [])  # hex 3 was full before and after, but unit 1 left it in the step

    def test_t_b_refutes_an_entry_straight_from_waiting(self) -> None:
        tau = 5
        waits = [(k, 0, 4, False, 0, tr.SPEED) for k in range(10, 10 + tau - 1)]  # waiting exactly tau - 1 steps
        ep = {"uid": 1, "start": 9, "target": 3, "path": (3,), "tau": tau, "steps": waits, "end": 14,
              "outcome": "entered"}
        self.assertEqual([ok for *_, ok in an.restart_events([ep])["T-b"]], [False])
        moving = dict(ep, steps=[(10, 0, 4, False, 0, tr.SPEED)] + [(k, 0.2, 3, False, 0, tr.SPEED) for k in range(11, 15)])
        self.assertEqual([ok for *_, ok in an.restart_events([moving])["T-b"]], [True])

    def test_channel_disagreement_makes_claims_inconclusive(self) -> None:
        t, _ = tr.contention_case("M1c")
        t.a[20][5] = t.a[20][5]._replace(speed=0.5)
        self.assertIn(I, an.targeted(t, 0, tr.line(5))["public"]["claims"].values())

    def test_verdict_thresholds(self) -> None:
        self.assertEqual([an.verdict([]), an.verdict([True] * 2), an.verdict([True] * 3), an.verdict([True, False, True]),
                          an.verdict([True] * 3, extra_ok=False)], ["NOT TESTED", "INSUFFICIENT", S, R, "INSUFFICIENT"])


class FidelityTest(unittest.TestCase):
    def test_f1_on_consistent_and_rival_data(self) -> None:
        t, orders = tr.contention_case("M1c")
        f1 = an.fidelity_f1(t, 0, tr.line(5), 0, orders, set())
        self.assertTrue(f1["pass"])
        self.assertEqual((f1["hex_sequences_differ"], f1["worst_step_offset"], f1["offset_histogram"]),
                         (0, 0, {"0": f1["observed_entries"]}))
        m1 = an.fidelity_f1(*(tr.contention_case("M1")[0], 0, tr.line(5), 0, orders, set()))
        self.assertFalse(m1["pass"])
        self.assertEqual(m1["worst_step_offset"], 4)

    def test_a_planted_two_step_delay_fails_f1(self) -> None:
        t, orders = tr.contention_case("M1c")
        entry = next(k for k in t.ks[1:] if t.b[k][5].hex == 3 and t.b[k - 1][5].hex == 2)
        for channel in (t.b, t.a):
            for k in (entry, entry + 1):
                channel[k][5] = channel[entry - 1][5]
        f1 = an.fidelity_f1(t, 0, tr.line(5), 0, orders, set())
        self.assertFalse(f1["pass"])
        self.assertEqual(f1["worst_step_offset"], 2)
        self.assertEqual(f1["offset_histogram"].get("-2"), 1)

    def test_a_capacity_violation_fails_f1(self) -> None:
        t, orders = tr.contention_case("M1c")
        for channel in (t.b, t.a):
            channel[30][77] = an.Row(3, (), 0, 0, 0, tr.SPEED, 2, 0, 0, 1, frozenset())
        self.assertFalse(an.fidelity_f1(t, 0, tr.line(5), 0, orders, set())["pass"])

    def test_an_observed_hex_above_capacity_fails_f1_on_its_own(self) -> None:
        units = [pm.Unit(i, 5, 36.0, 0) for i in (1, 2, 3, 4)] + [pm.Unit(9, 1, 36.0, 0)]
        orders = {0: [("move", 9, (2, 3))]}
        t, _ = tr.generate(units, tr.line(5), 80, orders)
        self.assertTrue(an.fidelity_f1(t, 0, tr.line(5), 0, orders, set())["pass"])
        for channel in (t.b, t.a):  # a fifth unit seen in hex 5 at one step only
            channel[50][77] = an.Row(5, (), 0, 0, 0, 36.0, 2, 0, 0, 1, frozenset())
        f1 = an.fidelity_f1(t, 0, tr.line(5), 0, orders, set())
        self.assertEqual((f1["hex_sequences_differ"], f1["capacity_or_adjacency_violations"]), (0, 0))
        self.assertEqual(f1["max_observed_occupancy"]["seat observation"], 5)
        self.assertFalse(f1["pass"])

    def test_the_two_validators_must_agree(self) -> None:
        from unittest import mock
        t, orders = tr.contention_case("M1c")
        with mock.patch.object(an.pm, "validate_trajectory", return_value=["planted disagreement"]):
            with self.assertRaises(an.Refused) as raised:
                an.fidelity_f1(t, 0, tr.line(5), 0, orders, set())
        self.assertIn("validators disagree", str(raised.exception))

    def test_a_removal_that_frees_a_place_is_applied(self) -> None:
        units = [pm.Unit(i, 3, 36.0, 0) for i in (1, 2, 3, 4)] + [pm.Unit(9, 1, 36.0, 0)]
        orders = {0: [("move", 9, (2, 3))]}
        t, _ = tr.generate(units, tr.line(5), 120, orders, remove={60: [2]})
        self.assertEqual(t.b[119][9].hex, 3)  # it got in once a place was freed
        f1 = an.fidelity_f1(t, 0, tr.line(5), 0, orders, set())
        self.assertTrue(f1["pass"], f1)
        self.assertEqual(an.removals(t.b, t.ks, 0), {60: [2]})

    def test_removals_mixed_speeds_and_lengths(self) -> None:
        units = [pm.Unit(1, 1, 36.0, 0), pm.Unit(2, 1, 5.0, 2), pm.Unit(3, 4, 36.0, 0)]
        orders = {0: [("move", 1, (2, 3, 4, 5)), ("move", 2, (2, 3))]}
        for steps in (40, 400):
            t, _ = tr.generate(units, tr.line(5), steps, orders)
            for channel in (t.b, t.a):  # unit 3 leaves the observation at step 30
                for k in t.ks:
                    if k >= 30:
                        channel[k].pop(3, None)
            f1 = an.fidelity_f1(t, 0, tr.line(5), 0, orders, set())
            self.assertTrue(f1["pass"], (steps, f1))
            self.assertEqual(f1["accounting"]["steps_compared"], steps)
        self.assertEqual(an.removals(t.b, t.ks, 0), {30: [3]})

    def test_a_unit_appearing_later_is_added_as_observed(self) -> None:
        units = [pm.Unit(1, 1, 36.0, 0), pm.Unit(2, 5, 36.0, 0)]
        orders = {0: [("move", 1, (2, 3))], 30: [("move", 2, (4, 3))]}
        t, _ = tr.generate(units, tr.line(5), 80, orders)
        for channel in (t.b, t.a):  # unit 2 is first observed at decision 20
            for k in range(20):
                channel[k].pop(2)
        f1 = an.fidelity_f1(t, 0, tr.line(5), 0, orders, set())
        self.assertTrue(f1["pass"], f1)
        self.assertEqual((f1["accounting"]["eligible_units"], f1["accounting"]["units_outside_population"]), (2, 0))
        self.assertEqual(an.appearances(t.b, t.ks, 0), {20: [2]})

    def test_a_replayed_stop_takes_effect_as_m3_says(self) -> None:
        units = [pm.Unit(i, 3, tr.SPEED, 0) for i in (1, 2, 3, 4)] + [pm.Unit(5, 2, tr.SPEED, 0)]
        orders = {0: [("move", 5, (3, 4))], 20: [("stop", 5, ())], 100: [("move", 5, (1,))]}
        t, log = tr.generate(units, tr.line(5), 120, orders)
        self.assertEqual(t.b[21][5].path, ())  # waiting in front of the full hex: stopped at once
        run = an.replay(t, 0, tr.line(5), 0, orders=orders)
        self.assertEqual((run.error, run.inapplicable), (None, {}))
        self.assertEqual(run.entries, an.observed_entries(t.b, t.ks, 0))
        early = {0: orders[0], 20: orders[20], 90: [("move", 5, (1,))]}  # inside the 75-step transition
        self.assertEqual(an.replay(t, 0, tr.line(5), 0, orders=early).inapplicable,
                         {"move: not applicable in the model state": 1})

    def test_f2_with_the_surrogate(self) -> None:
        units = [pm.Unit(1, 1, 36.0, 0), pm.Unit(2, 2, 36.0, 0)]
        t, log = tr.generate(units, tr.line(5), 120, surrogate=True, objectives={5: -1, 3: -1})
        moves = [(k, u, d) for kind, k, u, d in log if kind == "move"]
        occupations = [(k, u, h) for kind, k, u, h in log if kind == "occupy"]
        self.assertTrue(moves and occupations)
        f2 = an.fidelity_f2(t, 0, tr.line(5), 0, moves, occupations)
        self.assertTrue(f2["pass"], f2)
        wrong = [(k, u, 4) for k, u, _ in moves[:1]] + moves[1:]
        self.assertFalse(an.fidelity_f2(t, 0, tr.line(5), 0, wrong, occupations)["pass"])
        self.assertFalse(an.fidelity_f2(t, 0, tr.line(5), 0, moves, occupations[1:])["pass"])
        extra = moves + [(moves[0][0], moves[0][1], 4)]  # one more recorded order: same unit and step, another hex
        f2 = an.fidelity_f2(t, 0, tr.line(5), 0, extra, occupations)
        self.assertEqual((f2["orders"]["predicted_unmatched"], f2["orders"]["recorded_matched"]), (0, len(moves)))
        self.assertFalse(f2["pass"])


def p2(f1="PASS", f2="PASS", claims=None, occupancy=4, disagreements=0):
    claims = claims or {"T-a": S, "T-b": S, "T-c": "NOT TESTED", "T-d": S, "T-e": S}
    return {"F1": {"verdict": f1, "max_observed_occupancy": {"x": occupancy}}, "F2": {"verdict": f2},
            "targeted": {"claims": claims}, "channels": {"disagreeing_unit_entries": disagreements}}


def p1_out(e1=S, e2=S, e3=S, e4=S, outcomes=None):
    return {"verdicts": {"E1": e1, "E2": e2, "E3": e3, "E4": e4}, "evaluable": True,
            "outcomes": outcomes or {"accepted in place": 4}, "channels": {"disagreeing_unit_entries": 0},
            "max_occupancy": {"x": 4}, "premise": {"state_digests_equal_to_trigger": True},
            "integrity": {"replay_mismatches": 0, "gate_rejections": 0, "contract_errors": 0},
            "offline": {"pre_trigger_decisions_rechecked": 10}}


class GateTest(unittest.TestCase):
    def g(self, p1_, p2_, certificate=None):
        return an.gates(p1_, p2_, certificate)

    def test_the_gate_table(self) -> None:
        feasible = {"verdict": "feasible"}
        ready = self.g(p1_out(), p2(), feasible)
        self.assertEqual((ready["G2"], ready["G3"], ready["G5"]), ("PASS", "PASS", "READY_FOR_PROSPECTIVE_VALIDATION"))
        self.assertEqual(self.g(p1_out(), p2())["G3"], "UNRESOLVED")  # no certificate recomputed
        self.assertEqual(self.g(p1_out(e1=R, outcomes={"refused": 4}), p2())["G5"], "SHELVE")
        self.assertEqual(self.g(p1_out(e1=R, outcomes={"refused": 1, "accepted in place": 3}), p2())["G5"], "REVISE")
        self.assertEqual(self.g(p1_out(e2=R), p2(), feasible)["G5"], "REVISE")
        self.assertEqual(self.g(p1_out(e4=I), p2(), feasible)["G5"], "NEEDS_ENGINE_PROBE")
        self.assertEqual(self.g(p1_out(), p2(f1="FAIL"), feasible)["G3"], "FAIL")
        self.assertEqual(self.g(p1_out(), p2(f2="FAIL"), feasible)["G5"], "REVISE")
        self.assertEqual(self.g(p1_out(), p2(f1="INCONCLUSIVE"), feasible)["G3"], "UNRESOLVED")
